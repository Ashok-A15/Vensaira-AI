export default function Industries() {
  const sectionRef = useRef(null);

  useEffect(() => {
    if (!sectionRef.current) return;
    const prefersReduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
    const cards = sectionRef.current.querySelectorAll('.industry-card');
    const observer = new IntersectionObserver((entries) => {
      entries.forEach(entry => {
        if (entry.isIntersecting) {
          if (!prefersReduced) entry.target.style.opacity = '1';
          entry.target.style.transform = 'none';
          observer.unobserve(entry.target);
        }
      });
    }, { threshold: 0.08 });
    cards.forEach((card, i) => {
      if (!prefersReduced) {
        card.style.opacity = '0';
        card.style.transform = 'translateY(20px)';
        card.style.transition = `opacity 0.5s ease ${i * 0.05}s, transform 0.5s ease ${i * 0.05}s`;
      }
      observer.observe(card);
    });
    return () => observer.disconnect();
  }, []);

  return (
    <section className="section section-alt" id="industries" ref={sectionRef} aria-labelledby="industries-title">
      <div className="container">
        <div className="section-header">
          <h2 className="section-title gradient-text" id="industries-title">Industries We Can Serve</h2>
          <p className="section-description" style={{ maxWidth: 600, margin: '16px auto 0' }}>
            Our AI solutions can be adapted across multiple domains.
          </p>
        </div>

        <div className="industry-grid">
          {INDUSTRIES.map((ind) => (
            <div className="industry-card" key={ind.name}>
              <div className="industry-icon" aria-hidden="true">{ind.icon}</div>
              <span className="industry-name">{ind.name}</span>
            </div>
          ))}
        </div>
      </div>
    </section>
  );
}
